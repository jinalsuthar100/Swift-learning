 // Integer Learning
var age: Int = 25
print("I am \(age) years old.")


// Double Learning
var price : Double = 99.99
print("The price is $\(price).")

// Float learning
var temperature: Float = 36.6
print("The temperature is \(temperature) degrees Celsius.")

// Bool Learning
var isLoggedIn: Bool = true
print(isLoggedIn)


// String Learning
 var name: String = "Tanishq"
 print(name)

 // Character Learning
 var grade: Character = "A"
   print(grade)

// Array Learning
var fruits: [String] = ["Apple", "Banana", "Cherry"]
print("Output: \(fruits).  fb")


// Dictionary Learning
var person: [String:Any] = ["name": "Tanishq", "age": 25, "isStudent": true]
print("output: \(person)")

var fruitsBag: [String: Int] = ["Apple":5, "Banana":10, "Cherry":15]
print("output: \(fruitsBag)")

// Set Learning
var uniquenumbers: Set<Int> = [1,2,3,4,5]
print("output: \(uniquenumbers)")